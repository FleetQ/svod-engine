package dev.svod.engine.memory

import dev.svod.engine.core.Author
import dev.svod.engine.core.CommitInfo
import dev.svod.engine.core.GuardedWrite
import dev.svod.engine.core.SvodEngine
import dev.svod.engine.core.VaultPath
import dev.svod.engine.index.MarkdownChunker
import java.time.Instant
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter

/**
 * `svod-engine digest`: writes a generated `index.md` (the folder's notes with title, last change and
 * author/agent) and `log.md` (the folder's commits, newest first) into each folder, both in ONE guarded
 * commit through the single writer.
 *
 * The output depends only on git history (no "generated at" stamp), and digest commits are left out of
 * log.md, so a re-run with nothing new changes nothing. A file without the [MARKER] frontmatter was not
 * generated here and is never overwritten.
 */
object FolderDigest {

    const val MARKER = "generated: svod-folder-digest"
    private const val INDEX = "index.md"
    private const val LOG = "log.md"
    private const val MESSAGE_PREFIX = "digest: "
    private val DAY = DateTimeFormatter.ofPattern("yyyy-MM-dd").withZone(ZoneOffset.UTC)
    private val MINUTE = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm").withZone(ZoneOffset.UTC)

    data class Result(val written: List<String>, val unchanged: List<String>, val skipped: Map<String, String>)

    suspend fun run(engine: SvodEngine, folders: List<String> = emptyList(), maxLog: Int = 200): Result {
        val all = engine.list()
        val targets = folders.ifEmpty {
            all.filter { it.endsWith(".md") && '/' in it }.map { it.substringBefore('/') }.distinct().sorted()
        }
        val written = ArrayList<String>()
        val unchanged = ArrayList<String>()
        val skipped = LinkedHashMap<String, String>()
        for (raw in targets) {
            val folder = try {
                VaultPath.of(raw).value
            } catch (e: IllegalArgumentException) {
                skipped[raw] = "invalid folder: ${e.message}"
                continue
            }
            val indexPath = "$folder/$INDEX"
            val logPath = "$folder/$LOG"
            val currentIndex = engine.read(indexPath)
            val currentLog = engine.read(logPath)
            if (listOfNotNull(currentIndex, currentLog).any { !hasMarker(it.text) }) {
                skipped[folder] = "not generated by svod; refusing to overwrite"
                continue
            }
            val notes = all.filter { it.startsWith("$folder/") && it.endsWith(".md") && it != indexPath && it != logPath }
            if (notes.isEmpty()) {
                skipped[folder] = "no notes"
                continue
            }
            val index = renderIndex(engine, folder, notes)
            val log = renderLog(folder, engine.history(folder, maxLog))
            if (index == currentIndex?.text && log == currentLog?.text) {
                unchanged.add(folder)
                continue
            }
            val outcome = engine.writeGuarded(
                files = linkedMapOf(indexPath to index, logPath to log),
                guards = linkedMapOf(indexPath to currentIndex?.revision, logPath to currentLog?.revision),
                author = Author.SYSTEM,
                message = "$MESSAGE_PREFIX$folder",
            )
            when (outcome) {
                is GuardedWrite.Applied -> written.add(folder)
                is GuardedWrite.Stale -> skipped[folder] = "${outcome.path} changed while digesting; run again"
                is GuardedWrite.Blocked -> skipped[folder] = "blocked: ${outcome.findings.joinToString(", ")}"
            }
        }
        return Result(written, unchanged, skipped)
    }

    private fun hasMarker(text: String): Boolean {
        val lines = text.lines()
        if (lines.firstOrNull()?.trim() != "---") return false
        val end = lines.drop(1).indexOfFirst { it.trim() == "---" }
        if (end < 0) return false
        return lines.subList(1, end + 1).any { it.trim() == MARKER }
    }

    private fun header(what: String) =
        "---\n$MARKER\n---\n\n_$what. Regenerated by `svod-engine digest`; edits here are overwritten._\n"

    private fun who(name: String, agent: String?) = if (agent != null) "$name (agent $agent)" else name

    private suspend fun renderIndex(engine: SvodEngine, folder: String, notes: List<String>): String {
        val sb = StringBuilder(header("Notes in $folder/"))
        val groups = notes.sorted().groupBy { it.removePrefix("$folder/").substringBeforeLast('/', "") }
        for ((sub, paths) in groups.toSortedMap()) {
            sb.append('\n')
            if (sub.isNotEmpty()) sb.append("## $sub\n\n")
            for (path in paths) {
                val text = engine.read(path)?.text.orEmpty()
                val title = titleOf(text) ?: path.substringAfterLast('/').removeSuffix(".md")
                val last = engine.history(path, 1).firstOrNull()
                val change = last?.let { " — ${DAY.format(Instant.ofEpochSecond(it.epochSeconds))} · ${who(it.authorName, it.agent)}" }.orEmpty()
                sb.append("- [[${path.removeSuffix(".md")}|${title.replace("|", "-").replace("]", ")")}]]$change\n")
            }
        }
        return sb.toString()
    }

    private fun titleOf(text: String): String? {
        val parsed = MarkdownChunker.parse(text)
        parsed.title?.takeIf { it.isNotBlank() }?.let { return it }
        return parsed.body.lineSequence().firstOrNull { it.startsWith("# ") }?.removePrefix("# ")?.trim()?.takeIf { it.isNotEmpty() }
    }

    private fun renderLog(folder: String, commits: List<CommitInfo>): String {
        val sb = StringBuilder(header("Recent changes in $folder/, newest first"))
        sb.append('\n')
        val kept = commits.filter { !it.message.startsWith(MESSAGE_PREFIX) }
        if (kept.isEmpty()) sb.append("_No commits yet._\n")
        for (c in kept) {
            val subject = c.message.lineSequence().firstOrNull().orEmpty().trim()
            sb.append("- ${MINUTE.format(Instant.ofEpochSecond(c.epochSeconds))} · ${who(c.authorName, c.agent)} · $subject\n")
        }
        return sb.toString()
    }
}
