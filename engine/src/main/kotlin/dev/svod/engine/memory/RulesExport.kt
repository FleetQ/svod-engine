package dev.svod.engine.memory

import dev.svod.engine.core.SvodEngine
import dev.svod.engine.index.MarkdownChunker
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import kotlin.text.Charsets.UTF_8

/**
 * `svod-engine export-rules`: writes the vault's active policy, preference and procedure notes into a managed
 * section (between [BEGIN] and [END]) of an agent instructions file outside the vault (AGENTS.md, CLAUDE.md).
 *
 * Filtering mirrors context_pack's lifecycle rules: no revoked, provisional, superseded or expired notes, no
 * `private: true` notes, nothing under messy/ or a dot-folder. The section holds no timestamp, so the output
 * depends only on the vault and the expiry cutoff; the file is rewritten only when its bytes change, and text
 * outside the markers is kept byte-for-byte.
 */
object RulesExport {

    const val BEGIN = "<!-- svod:rules:begin -->"
    const val END = "<!-- svod:rules:end -->"
    val RULE_TYPES = listOf("policy", "preference", "procedure")
    private val HEADINGS = mapOf("policy" to "Policies", "preference" to "Preferences", "procedure" to "Procedures")

    data class Rule(val path: String, val type: String, val title: String, val commit: String?, val body: String)

    data class Result(val changed: Boolean, val rules: Int, val target: Path)

    /** Active rule notes, ordered by [RULE_TYPES] then path. */
    suspend fun collect(engine: SvodEngine, nowEpoch: Long): List<Rule> {
        val out = ArrayList<Rule>()
        for ((path, raw) in engine.readAllNotes()) {
            if (path.startsWith("messy/") || path.split('/').any { it.startsWith(".") }) continue
            val doc = MarkdownChunker.parse(raw)
            val type = doc.type ?: continue
            if (type !in RULE_TYPES || doc.private) continue
            if (doc.status == "revoked" || doc.status == "provisional") continue
            if (doc.supersededBy != null) continue
            if (doc.expiresAt != null && doc.expiresAt <= nowEpoch) continue
            val title = doc.title?.trim()?.takeIf { it.isNotEmpty() }
                ?: doc.body.lineSequence().firstOrNull { it.startsWith("# ") }?.removePrefix("# ")?.trim()?.takeIf { it.isNotEmpty() }
                ?: path.substringAfterLast('/').removeSuffix(".md")
            val commit = engine.history(path, 1).firstOrNull()?.commit
            out.add(Rule(path, type, title, commit, MarkdownChunker.stripPrivateSpans(doc.body).trim()))
        }
        return out.sortedWith(compareBy<Rule>({ RULE_TYPES.indexOf(it.type) }, { it.path }))
    }

    /** The managed section, from [BEGIN] to [END] (no trailing newline). */
    fun render(rules: List<Rule>): String {
        val sb = StringBuilder()
        sb.append(BEGIN).append('\n')
        sb.append("_Generated by `svod-engine export-rules` from the Svod vault; edits between these markers are overwritten._\n")
        if (rules.isEmpty()) sb.append("\n_No active rules._\n")
        for (type in RULE_TYPES) {
            val group = rules.filter { it.type == type }
            if (group.isEmpty()) continue
            sb.append("\n## ").append(HEADINGS.getValue(type)).append('\n')
            for (r in group) {
                sb.append("\n### ").append(r.title.replace('\n', ' ')).append('\n')
                sb.append("_Source: `").append(r.path).append("` @ ").append(r.commit?.take(12) ?: "uncommitted").append("_\n")
                val body = r.body.replace("\r\n", "\n")
                if (body.isNotEmpty()) sb.append('\n').append(body).append('\n')
            }
        }
        sb.append(END)
        return sb.toString()
    }

    /** [existing] with its managed section replaced by [section] (or [section] appended when there is none). */
    fun splice(existing: String?, section: String, file: String = "the target file"): String {
        if (existing.isNullOrBlank()) return section + "\n"
        val begins = occurrences(existing, BEGIN)
        val ends = occurrences(existing, END)
        if (begins.isEmpty() && ends.isEmpty()) return existing.trimEnd('\n') + "\n\n" + section + "\n"
        require(begins.size == 1 && ends.size == 1 && begins[0] < ends[0]) {
            "managed section markers are malformed in $file; fix or remove them"
        }
        return existing.substring(0, begins[0]) + section + existing.substring(ends[0] + END.length)
    }

    private fun occurrences(text: String, marker: String): List<Int> {
        val out = ArrayList<Int>()
        var i = text.indexOf(marker)
        while (i >= 0) {
            out.add(i)
            i = text.indexOf(marker, i + marker.length)
        }
        return out
    }

    /** Render and splice into [target]; writes atomically, and only when the content changes. */
    suspend fun export(
        engine: SvodEngine,
        vaultRoot: Path,
        target: Path,
        nowEpoch: Long = System.currentTimeMillis() / 1000,
    ): Result {
        val abs = target.toAbsolutePath().normalize()
        val root = vaultRoot.toAbsolutePath().normalize()
        val realRoot = runCatching { root.toRealPath() }.getOrDefault(root)
        // Vault files are written only through the single writer.
        require(!abs.startsWith(root) && !abs.startsWith(realRoot) && !realParent(abs).startsWith(realRoot)) {
            "target $target is inside the vault; export-rules writes only outside it"
        }
        val rules = collect(engine, nowEpoch)
        val existing = if (Files.exists(abs)) Files.readString(abs, UTF_8) else null
        val next = splice(existing, render(rules), abs.toString())
        if (next == existing) return Result(false, rules.size, abs)
        val dir = abs.parent
        Files.createDirectories(dir)
        val tmp = Files.createTempFile(dir, ".${abs.fileName}.", ".tmp")
        try {
            Files.writeString(tmp, next, UTF_8)
            Files.move(tmp, abs, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
        } finally {
            Files.deleteIfExists(tmp)
        }
        return Result(true, rules.size, abs)
    }

    /** [p] with its nearest existing ancestor resolved through symlinks. */
    private fun realParent(p: Path): Path {
        var existing: Path? = p
        while (existing != null && !Files.exists(existing)) existing = existing.parent
        if (existing == null) return p
        return runCatching { existing.toRealPath().resolve(existing.relativize(p)).normalize() }.getOrDefault(p)
    }
}
